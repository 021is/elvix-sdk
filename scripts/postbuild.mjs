/**
 * Postbuild fixups:
 *
 *  1. esbuild keeps `"use client"` only on some outputs and never on a shared
 *     chunk, and Next's App Router treats a module without it as a Server
 *     Component and crashes on createContext. Everything in dist/react/ is
 *     client code (the React build has its own outDir, see tsup.config.ts),
 *     so every file there gets the directive, EXCEPT the entry, index.js:
 *     a `"use client"` entry is one client reference holding every export,
 *     and Turbopack then ships all of it (measured: 249 KB gzip for the
 *     provider and the badge, 22 KB without it). The entry only re-exports
 *     from client files, which tests/bundle-split.test.ts checks.
 *     Idempotent.
 *
 *  2. Ship a `dist/styles.css.d.ts` ambient declaration so strict-tsconfig
 *     consumers can `import "@elvix.is/sdk/styles.css"` without hand-rolling
 *     a globals.d.ts shim. Cycle-2 friction: install.md says "REQUIRED" for
 *     the stylesheet import but every Next + strict TS user got a TS2307
 *     until they wrote their own ambient module. Wired via the
 *     `exports["./styles.css"].types` field in package.json.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const reactDir = "dist/react";
const entry = "index.js";
const directive = '"use client";';
let prepended = 0;
for (const name of readdirSync(reactDir)) {
  if (!name.endsWith(".js") || name === entry) continue;
  const file = join(reactDir, name);
  const src = readFileSync(file, "utf8");
  if (src.startsWith(directive) || src.startsWith("'use client'")) continue;
  writeFileSync(file, `${directive}\n${src}`);
  prepended += 1;
}
console.log(`postbuild: "use client" prepended to ${prepended} files in ${reactDir}`);

const stylesDts = `// Generated by scripts/postbuild.mjs. Ambient declaration so strict-tsconfig
// consumers can \`import "@elvix.is/sdk/styles.css"\` without writing their own
// globals.d.ts shim. The CSS itself is the same file Tailwind compiled into
// dist/styles.css — this only teaches TypeScript that the import resolves.
declare module "@elvix.is/sdk/styles.css";
`;
writeFileSync("dist/styles.css.d.ts", stylesDts);
console.log("postbuild: wrote dist/styles.css.d.ts");
